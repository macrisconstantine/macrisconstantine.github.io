const cache = new Map();

function makeCanvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  const x = c.getContext('2d');
  x.imageSmoothingEnabled = false;
  return [c, x];
}

/**
 * Paint a text sprite to an off-screen canvas, adding a 1px dark outline so
 * every object reads against any floor. Results are cached per accent colour.
 */
export function sprite(name, accent) {
  const key = name + '|' + (accent || '');
  if (cache.has(key)) return cache.get(key);

  const rows = ART[name];
  if (!rows) throw new Error('no sprite: ' + name);

  const w = rows[0].length, h = rows.length;
  const pad = 1;
  const [cv, ctx] = makeCanvas(w + pad * 2, h + pad * 2);

  // Pass 1 — the pixels themselves.
  const solid = [];
  for (let y = 0; y < h; y++) {
    solid[y] = [];
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      const col = ch === ACCENT_KEY ? (accent || '#9aa6b5') : PAL[ch];
      solid[y][x] = !!col;
      if (col) { ctx.fillStyle = col; ctx.fillRect(x + pad, y + pad, 1, 1); }
    }
  }

  // Pass 2 — outline: any empty cell orthogonally touching a solid one.
  ctx.fillStyle = 'rgba(10,8,18,0.85)';
  for (let y = -1; y <= h; y++) {
    for (let x = -1; x <= w; x++) {
      if (solid[y] && solid[y][x]) continue;
      const near =
        (solid[y - 1] && solid[y - 1][x]) ||
        (solid[y + 1] && solid[y + 1][x]) ||
        (solid[y] && solid[y][x - 1]) ||
        (solid[y] && solid[y][x + 1]);
      if (near) ctx.fillRect(x + pad, y + pad, 1, 1);
    }
  }

  const out = { canvas: cv, w: cv.width, h: cv.height, pad };
  cache.set(key, out);
  return out;
}

/** Horizontally mirrored variant, used so one side-view sprite faces both ways. */
export function spriteFlipped(name, accent) {
  const key = name + '|' + (accent || '') + '|flip';
  if (cache.has(key)) return cache.get(key);
  const src = sprite(name, accent);
  const [cv, ctx] = makeCanvas(src.w, src.h);
  ctx.translate(src.w, 0);
  ctx.scale(-1, 1);
  ctx.drawImage(src.canvas, 0, 0);
  const out = { canvas: cv, w: src.w, h: src.h, pad: src.pad };
  cache.set(key, out);
  return out;
}

